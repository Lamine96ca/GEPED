def _charger_env(fichier):
    """
    Variables du fichier .env (production, chez o2switch) : une ligne NOM=valeur, # pour un
    commentaire. Une variable déjà définie dans l'environnement (cPanel) n'est pas remplacée.
    Le fichier .env n'est JAMAIS envoyé sur Git (voir .gitignore et .env.exemple).
    """
    if not fichier.exists():
        return
    for ligne in fichier.read_text(encoding='utf-8').splitlines():
        ligne = ligne.strip()
        if not ligne or ligne.startswith('#') or '=' not in ligne:
            continue
        nom, valeur = ligne.split('=', 1)
        valeur = valeur.strip()
        if len(valeur) >= 2 and valeur[0] == valeur[-1] and valeur[0] in '"\'':
            valeur = valeur[1:-1]
        os.environ.setdefault(nom.strip(), valeur)


_charger_env(BASE_DIR / '.env')


def _liste(nom):
    return [v.strip() for v in os.environ.get(nom, '').split(',') if v.strip()]


def _cle_secrete():
    """
    Clé secrète : variable d'environnement GPED_SECRET_KEY (production), sinon le fichier local
    config/cle_secrete.txt, créé au premier lancement. Jamais écrite dans le code ni envoyée sur Git.
    """
    cle = os.environ.get('GPED_SECRET_KEY', '').strip()
    if cle:
        return cle
    fichier = BASE_DIR / 'config' / 'cle_secrete.txt'
    if fichier.exists() and fichier.read_text(encoding='utf-8').strip():
        return fichier.read_text(encoding='utf-8').strip()
    from django.core.management.utils import get_random_secret_key
    cle = get_random_secret_key()
    fichier.write_text(cle, encoding='utf-8')
    return cle


